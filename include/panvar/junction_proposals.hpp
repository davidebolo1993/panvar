#pragma once

// M9-G (EXPERIMENTAL, default off; profile key repair_junction_proposals off|experimental_v1): junction-aware local-pair
// proposals (rule JP1.1) for repair blocks whose existing allele-pair proposal emissions are ALL tied. A search heuristic
// only: it chooses which local pairs the repair neighbourhood generates; it is not a likelihood, a confidence value or a
// final-score term, and the repair's fragment / exposure / copying-prior objective is unchanged.
//
// JP1.1 = M9-F's frozen JP1 with one declared change, the residual tie-break:
//   window   W(h, a) = L_h + allele a + R_h; L_h / R_h the last / first K-1 bases of incumbent homologue h around the block
//   markers  every canonical K-mer (K = 31; canonical = min of the forward and reverse-complement 2-bit codes, the caller's
//            convention); K-mers with a non-ACGT base are skipped (a declared deviation from the closed-syncmer markers)
//   inventory  the distinct canonical K-mers over W(h, a) for every allele a and both homologues (fixed per invocation)
//   copies   n(m, W(1, x)) + n(m, W(2, y)) + e(m), e(m) = occurrences in both incumbent haplotypes outside the windows
//   reads    y(m) = occurrences of canonical m in every read of every pair (both mates)
//   score    sum over the inventory of y log(rate copies + background) - (rate copies + background), as an exact delta over
//            the K-mers the candidate's windows touch, summed in ascending inventory order (deterministic)
//   pair     {x, y} ranked by max over the two homologue assignments; both assignments are generated by the repair
//   ties     |dS| <= 1e-9, chained from the class head; inside a tie class the order is CONTENT-based -- the sorted pair of
//            allele sequences, lexicographically (JP1 used allele indices; JP1.1 is permutation-invariant) -- and the
//            shortlist is the first `limit` pairs; the tie class at the cutoff is reported
#include "panvar/genotype_model.hpp"

#include <cstddef>
#include <cstdint>
#include <map>
#include <memory>
#include <string>
#include <utility>
#include <vector>

namespace panvar {

inline constexpr std::size_t kJunctionK = 31;
inline constexpr double kJunctionTieNats = 1e-9;

// Sample-scoped read K-mer counts: every canonical K-mer of every read (both mates), sorted with its count. Built once per
// run from the run's own fragments and shared read-only by every search of that run; bounded by the read data.
struct JunctionReadKmers {
    std::vector<std::uint64_t> codes;
    std::vector<std::uint32_t> counts;
    std::uint64_t reads = 0;
    std::uint64_t occurrences = 0;
    static JunctionReadKmers from_fragments(const std::vector<ReadPair>& fragments);
    std::uint32_t count(std::uint64_t code) const;
    std::size_t bytes() const { return codes.size() * sizeof(std::uint64_t) + counts.size() * sizeof(std::uint32_t); }
};

// Every canonical K-mer of `sequence` with the 0-based start of its K-mer, skipping windows with a non-ACGT base.
std::vector<std::pair<std::uint64_t, std::size_t>> junction_kmers(const std::string& sequence);

// The incumbent around one block: per homologue the spelled prefix (blocks before), the incumbent allele index at the block
// and the spelled suffix (blocks after).
struct JunctionContext {
    std::string prefix[2];
    std::string suffix[2];
    std::size_t incumbent[2] = {0, 0};
};

struct JunctionProposal {
    std::vector<std::pair<std::size_t, std::size_t>> pairs;   // the shortlist, x <= y
    std::vector<double> scores;                               // best-assignment score of each shortlisted pair
    std::size_t inventory = 0, observed = 0, elsewhere = 0;
    std::size_t candidate_pairs = 0, distinct_scores = 0;
    std::size_t cutoff_tie_size = 0;
    bool cutoff_tie_crosses = false;                          // the tie class at the cutoff continues past it
};

// All-pair ranking (exposed for the gates and the probe): one row per unordered pair x <= y in JP1.1 order.
struct JunctionPairScore {
    std::size_t x = 0, y = 0;
    double ab = 0.0, ba = 0.0, best = 0.0;
    std::size_t tie_class = 0;
};
std::vector<JunctionPairScore> junction_rank_all(const std::vector<std::string>& alleles, const JunctionContext& context,
                                                 const JunctionReadKmers& reads, double rate, double background,
                                                 JunctionProposal* summary = nullptr);

JunctionProposal junction_local_pairs(const std::vector<std::string>& alleles, const JunctionContext& context,
                                      const JunctionReadKmers& reads, double rate, double background, std::size_t limit);

// True when every unordered allele pair of the block has exactly the same proposal emission and the block has more pairs
// than the local-pair limit (with no more pairs than the limit every pair is generated anyway: nothing to choose).
bool junction_block_eligible(const std::vector<double>& pair_emissions, std::size_t limit);

// A bounded, search-scoped memo keyed by the COMPLETE dependency of one invocation: the block and the incumbent's unordered
// pair of whole label paths (which fixes both flanks and every elsewhere multiplicity); the reads, rate and background are
// fixed for the search. Least-recently-inserted eviction at `capacity` entries.
class JunctionProposalCache {
public:
    explicit JunctionProposalCache(std::size_t capacity = 16) : capacity_(capacity) {}
    using Key = std::pair<std::size_t, std::pair<std::vector<std::size_t>, std::vector<std::size_t>>>;
    static Key key(std::size_t block, const std::vector<std::size_t>& first, const std::vector<std::size_t>& second);
    const JunctionProposal* find(const Key& key);
    const JunctionProposal& insert(const Key& key, JunctionProposal value);
    std::uint64_t hits() const { return hits_; }
    std::uint64_t misses() const { return misses_; }
    std::size_t size() const { return entries_.size(); }

private:
    std::size_t capacity_;
    std::map<Key, JunctionProposal> entries_;
    std::vector<Key> order_;
    std::uint64_t hits_ = 0, misses_ = 0;
};

}  // namespace panvar
