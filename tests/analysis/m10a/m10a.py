#!/usr/bin/env python3
"""M10-A campaign helpers (frozen with DESIGN.md; nothing here genotypes).

  m10a.py declare <out>    per-model declaration artifacts for the three development models (cyp2d6_block_alleles dump +
                           degeneracy_inventory.py + compound_interval_declarations_v1), each bound to its fingerprint; the
                           dump fingerprints must equal the ones S2-L recorded for the same inputs
  m10a.py controls <out>   comparator controls on saved runs and relocated, deliberately altered copies
  m10a.py summary <out>    per-run and per-comparison tables
"""
import csv
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
R = "/Users/davide.bolognini/panvar/tests/results"
OUT = f"{R}/m10a_dev_configuration_20261020"
PERF = f"{R}/genotype_perf_bounded_20261015"
S2L = f"{R}/s2l_cross_locus_20261019/runs"
EXPECTED_FP = {"c4": "d2b8c6c2e0b4079d", "cyp": "2a5b720a1c5bf669", "acot": "d622742f9cf8e7a5"}   # S2-L summary, same inputs
LOCUS_CELL = {"c4": "c4_5", "cyp": "cyp_5", "acot": "acot_5"}
T = lambda p: list(csv.DictReader((l for l in open(p) if not l.startswith("#")), delimiter="\t")) if os.path.exists(p) else []
KV = lambda p: dict(l.rstrip("\n").split("\t", 1) for l in open(p) if "\t" in l and not l.startswith("#")) if os.path.exists(p) else {}


def cells():
    return {r["id"]: r for r in csv.DictReader(open(f"{PERF}/cells.tsv"), delimiter="\t")}


def write(out, name, rows):
    with open(f"{out}/{name}.tsv", "w") as f:
        if not rows:
            f.write("none\n")
            return
        w = csv.DictWriter(f, fieldnames=list(dict.fromkeys(k for r in rows for k in r)), delimiter="\t", lineterminator="\n", restval="")
        w.writeheader()
        w.writerows(rows)


def declare(out):
    c, rows, specs = cells(), [], []
    for locus, cell in LOCUS_CELL.items():
        x = c[cell]
        code = subprocess.run([f"{WT}/build/cyp2d6_block_alleles", x["graph"], x["reference"], x["curation"], f"{out}/{locus}"]).returncode
        if code:
            return code
        specs.append(f"{locus}={out}/{locus}")
    code = subprocess.run([sys.executable, f"{WT}/tests/analysis/cyp2d6_pilot/degeneracy_inventory.py", f"{out}/degeneracy.tsv",
                           f"{out}/degeneracy_summary.tsv", *specs]).returncode
    if code:
        return code
    ok = True
    for locus in LOCUS_CELL:
        fp = KV(f"{out}/{locus}.summary.tsv")["model_fingerprint"]
        order = []
        for r in T(f"{out}/{locus}.block_alleles.tsv"):
            if not order or order[-1] != r["block_id"]:
                order.append(r["block_id"])
        inv = next(r for r in T(f"{out}/degeneracy_summary.tsv") if r["model"] == locus)
        assert inv["model_fingerprint"] == fp
        intervals = [] if inv["coalescence_intervals"] in ("", "none", "NA") else inv["coalescence_intervals"].split(",")
        lines = ["# compound_interval_declarations_v1", f"# generated by tests/analysis/m10a/m10a.py declare from {out}/degeneracy_summary.tsv "
                 f"(model {locus}); conservative, not claimed minimal or exhaustive", f"model_fingerprint\t{fp}", f"block_ids\t{','.join(order)}"]
        for k, iv in enumerate(intervals, 1):
            a, b = iv.split("..")
            ids = order[order.index(a):order.index(b) + 1]
            lines.append(f"interval\tinventory_{k}\t{','.join(ids)}\tdegeneracy_inventory_v1:cross_block_equivalences={inv['cross_block_equivalences']}")
        open(f"{out}/{locus}.declarations.tsv", "w").write("\n".join(lines) + "\n")
        match = fp.startswith(EXPECTED_FP[locus])
        ok = ok and match
        rows.append(dict(locus=locus, fingerprint=fp, expected_prefix=EXPECTED_FP[locus], fingerprint_matches_s2l=match, blocks=len(order),
                         intervals=";".join(intervals) or "none", cross_block_equivalences=inv["cross_block_equivalences"]))
    write(out, "declarations", rows)
    print(open(f"{out}/declarations.tsv").read())
    return 0 if ok else 1


def compare(mode, a, b, out):
    return subprocess.run([sys.executable, os.path.join(HERE, "m10a_compare.py"), mode, a, b, out], capture_output=True, text=True).returncode


def relocated(src, dst, edit=None):
    shutil.copytree(src, dst)
    for f in os.listdir(dst):   # relocate absolute paths so normalisation sees the copy as the same run
        p = os.path.join(dst, f)
        if os.path.isfile(p) and not f.endswith(".fa"):
            t = open(p, errors="replace").read()
            if src in t:
                open(p, "w").write(t.replace(src, dst))
    if edit:
        edit(dst)
    return dst


def add_status(rows):
    def f(d):
        with open(os.path.join(d, "call.mosaic_status.tsv"), "a") as s:
            s.write("".join(f"{k}\t{v}\n" for k, v in rows))
    return f


def bump_score(d):
    p = os.path.join(d, "call.mosaic_scores.tsv")
    lines = open(p).read().split("\n")
    f = lines[1].split("\t")
    f[-1] = f[-1] + "1" if f[-1] else "1"
    lines[1] = "\t".join(f)
    open(p, "w").write("\n".join(lines))


def controls(out):
    # S2-L predates the annotation: a relocated copy with a header-only annotation file stands in for an annotated run
    base = relocated(f"{S2L}/combined.c4_5", f"{out}/base",
                     lambda d: open(os.path.join(d, "call.sequence_compound.tsv"), "w").write("interval\tstatus\n"))
    jp_rows = [("junction_eligible_blocks", "0"), ("junction_invocations", "0")]
    settings_jp = lambda d: open(os.path.join(d, "call.settings.tsv"), "a").write("repair_junction_proposals\texperimental_v1\tprofile x\n")
    s2a = f"{R}/s2a_early_incumbent_20261018/runs"
    p1 = f"{R}/p1_consolidation_20261017/runs"
    cases = [
        ("C1 route: S2-L control vs combined (C4 5x)", "route", f"{S2L}/control.c4_5", f"{S2L}/combined.c4_5", 0),
        ("C2 route: S2-A early incumbent off vs on (C4 5x)", "route", f"{s2a}/c4.off", f"{s2a}/c4.on", 0),
        ("C3 route: one score altered", "route", f"{S2L}/combined.c4_5", relocated(f"{S2L}/combined.c4_5", f"{out}/c3", bump_score), 1),
        ("C4 jp: eligible 0, otherwise identical", "jp", base, relocated(base, f"{out}/c4", lambda d: (add_status(jp_rows)(d), settings_jp(d))), 0),
        ("C5 jp: eligible 0 and a score altered", "jp", base,
         relocated(base, f"{out}/c5", lambda d: (add_status(jp_rows)(d), settings_jp(d), bump_score(d))), 1),
        ("C6 jp: eligible 1 and a score altered (JP-attributable)", "jp", base,
         relocated(base, f"{out}/c6", lambda d: (add_status([("junction_eligible_blocks", "1")])(d), settings_jp(d), bump_score(d))), 0),
        ("C7 prepared: prepared rows added", "prepared", base,
         relocated(base, f"{out}/c7", add_status([("prepared_locus", "1"), ("prepared_locus_origin", "loaded")])), 0),
        ("C8 prepared: an undeclared setting changed", "prepared", base,
         relocated(base, f"{out}/c8", lambda d: open(os.path.join(d, "call.settings.tsv"), "a").write("mismatch_band\t7\tprofile x\n")), 1),
        ("C9 backend: P1 opt vs reference (C4 5x; P1 PASS)", "backend", f"{p1}/o.c4_5", f"{p1}/r.c4_5", 0),
        ("C10 repeat: S2-L ACOT 30x combined vs its repeat", "repeat", f"{S2L}/combined.acot_30", f"{S2L}/combined.acot_30.repeat", 0),
    ]
    rows = []
    for label, mode, a, b, want in cases:
        got = compare(mode, a, b, f"{out}/{label.split()[0]}.tsv")
        rows.append(dict(control=label, mode=mode, expected_exit=want, exit=got, ok=got == want))
    write(out, "controls", rows)
    print(open(f"{out}/controls.tsv").read())
    return 0 if all(r["ok"] for r in rows) else 1


def summary(out):
    runs, cmps = [], []
    for u in sorted(os.listdir(f"{OUT}/runs")):
        d = f"{OUT}/runs/{u}"
        prefixes = [(u, f"{d}/call")] if os.path.exists(f"{d}/call.mosaic_status.tsv") else \
                   [(f"{u}/{s}", f"{d}/{s}/call") for s in sorted(os.listdir(d)) if os.path.exists(f"{d}/{s}/call.mosaic_status.tsv")]
        for name, p in prefixes:
            st, sl = KV(p + ".mosaic_status.tsv"), KV(p + ".sequence_locus.tsv")
            comp = T(p + ".sequence_compound.tsv")
            runs.append(dict(run=name, status=st.get("status"), prediction=sl.get("prediction"), sequence_status=sl.get("sequence_status"),
                             junction_eligible_blocks=st.get("junction_eligible_blocks", "-"),
                             compound=";".join(f"{c['interval']}:{c['status']}:{c['target_resolution']}:err<={c['error_upper']}" for c in comp) or "none",
                             seconds_total=st.get("seconds_total"), peak_footprint_bytes=st.get("resources_phys_footprint_peak_bytes"),
                             prepared_locus=st.get("prepared_locus_origin", "cold"), model_fingerprint=st.get("model_fingerprint")))
        if u.startswith("cmp.") and os.path.exists(f"{d}/compare.tsv"):
            kv = KV(f"{d}/compare.tsv")
            cmps.append(dict(comparison=u, verdict=kv.get("verdict"), science_identical=kv.get("science_identical", "-"),
                             junction_eligible_blocks=kv.get("junction_eligible_blocks", "-")))
    write(out, "runs", runs)
    write(out, "comparisons", cmps)
    print(open(f"{out}/runs.tsv").read() + "\n" + open(f"{out}/comparisons.tsv").read())
    return 0


if __name__ == "__main__":
    mode, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    sys.exit({"declare": declare, "controls": controls, "summary": summary}[mode](out))
