"""M10-A campaign helpers (frozen with DESIGN.md; nothing here genotypes).

  m10a.py declare <out>    per-model declaration artifacts for the three development models (cyp2d6_block_alleles dump +
                           degeneracy_inventory.py + compound_interval_declarations_v1), each bound to its fingerprint; the
                           dump fingerprints must equal the ones S2-L recorded for the same inputs
  m10a.py controls <out>   comparator controls on saved runs and relocated, deliberately altered copies
  m10a.py summary <out>    per-run and per-comparison tables
"""
