HERE = os.path.dirname(os.path.abspath(__file__))
WT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
R = "/Users/davide.bolognini/panvar/tests/results"
OUT = f"{R}/m10a_dev_configuration_20261020"
PERF = f"{R}/genotype_perf_bounded_20261015"
S2L = f"{R}/s2l_cross_locus_20261019/runs"
EXPECTED_FP = {"c4": "d2b8c6c2e0b4079d", "cyp": "2a5b720a1c5bf669", "acot": "d622742f9cf8e7a5"}   # S2-L summary, same inputs
LOCUS_CELL = {"c4": "c4_5", "cyp": "cyp_5", "acot": "acot_5"}
T = lambda p: list(csv.DictReader((l for l in open(p) if not l.startswith("#")), delimiter="\t")) if os.path.exists(p) else []
KV = lambda p: dict(l.rstrip("\n").split("\t", 1) for l in open(p) if "\t" in l and not l.startswith("#")) if os.path.exists(p) else {}


def cells():
    return {r["id"]: r for r in csv.DictReader(open(f"{PERF}/cells.tsv"), delimiter="\t")}


def write(out, name, rows):
    with open(f"{out}/{name}.tsv", "w") as f:
        if not rows:
            f.write("none\n")
            return
        w = csv.DictWriter(f, fieldnames=list(dict.fromkeys(k for r in rows for k in r)), delimiter="\t", lineterminator="\n", restval="")
        w.writeheader()
        w.writerows(rows)


def declare(out):
    c, rows, specs = cells(), [], []
    for locus, cell in LOCUS_CELL.items():
        x = c[cell]
        code = subprocess.run([f"{WT}/build/cyp2d6_block_alleles", x["graph"], x["reference"], x["curation"], f"{out}/{locus}"]).returncode
        if code:
            return code
        specs.append(f"{locus}={out}/{locus}")
    code = subprocess.run([sys.executable, f"{WT}/tests/analysis/cyp2d6_pilot/degeneracy_inventory.py", f"{out}/degeneracy.tsv",
                           f"{out}/degeneracy_summary.tsv", *specs]).returncode
    if code:
        return code
    ok = True
    for locus in LOCUS_CELL:
        fp = KV(f"{out}/{locus}.summary.tsv")["model_fingerprint"]
        order = []
        for r in T(f"{out}/{locus}.block_alleles.tsv"):
            if not order or order[-1] != r["block_id"]:
                order.append(r["block_id"])
        inv = next(r for r in T(f"{out}/degeneracy_summary.tsv") if r["model"] == locus)
        assert inv["model_fingerprint"] == fp
        intervals = [] if inv["coalescence_intervals"] in ("", "none", "NA") else inv["coalescence_intervals"].split(",")
        lines = ["# compound_interval_declarations_v1", f"# generated by tests/analysis/m10a/m10a.py declare from {out}/degeneracy_summary.tsv "
                 f"(model {locus}); conservative, not claimed minimal or exhaustive", f"model_fingerprint\t{fp}", f"block_ids\t{','.join(order)}"]
        for k, iv in enumerate(intervals, 1):
            a, b = iv.split("..")
            ids = order[order.index(a):order.index(b) + 1]
            lines.append(f"interval\tinventory_{k}\t{','.join(ids)}\tdegeneracy_inventory_v1:cross_block_equivalences={inv['cross_block_equivalences']}")
        open(f"{out}/{locus}.declarations.tsv", "w").write("\n".join(lines) + "\n")
        match = fp.startswith(EXPECTED_FP[locus])
        ok = ok and match
        rows.append(dict(locus=locus, fingerprint=fp, expected_prefix=EXPECTED_FP[locus], fingerprint_matches_s2l=match, blocks=len(order),
                         intervals=";".join(intervals) or "none", cross_block_equivalences=inv["cross_block_equivalences"]))
    write(out, "declarations", rows)
    print(open(f"{out}/declarations.tsv").read())
    return 0 if ok else 1


def compare(mode, a, b, out):
    return subprocess.run([sys.executable, os.path.join(HERE, "m10a_compare.py"), mode, a, b, out], capture_output=True, text=True).returncode


def relocated(src, dst, edit=None):
    shutil.copytree(src, dst)
    for f in os.listdir(dst):   # relocate absolute paths so normalisation sees the copy as the same run
        p = os.path.join(dst, f)
        if os.path.isfile(p) and not f.endswith(".fa"):
            t = open(p, errors="replace").read()
            if src in t:
                open(p, "w").write(t.replace(src, dst))
    if edit:
        edit(dst)
    return dst


def add_status(rows):
    def f(d):
        with open(os.path.join(d, "call.mosaic_status.tsv"), "a") as st:
            st.write("".join(f"{k}\t{v}\n" for k, v in rows))
    return f


def set_kv(fname, key, value):   # replace one key's value in a key<TAB>value[<TAB>source] file (settings or status)
    def f(d):
        p = os.path.join(d, fname)
        lines = open(p).read().split("\n")
        hit = 0
        for i, line in enumerate(lines):
            x = line.split("\t")
            if x[0] == key:
                x[1] = value
                lines[i] = "\t".join(x)
                hit += 1
        assert hit == 1, (fname, key, hit)
        open(p, "w").write("\n".join(lines))
    return f


def set_column(fname, column, value, row_pred=lambda r: True):   # Amendment 1: alter a named column, never by position
    def f(d):
        p = os.path.join(d, fname)
        lines = open(p).read().split("\n")
        head = next(i for i, l in enumerate(lines) if l and not l.startswith("#"))
        cols = lines[head].split("\t")
        j = cols.index(column)
        for i in range(head + 1, len(lines)):
            x = lines[i].split("\t")
            if len(x) == len(cols) and row_pred(dict(zip(cols, x))):
                x[j] = value(x[j])
                lines[i] = "\t".join(x)
                open(p, "w").write("\n".join(lines))
                return
        raise AssertionError(f"no row of {fname} matched")
    return f


def bump_score(d):
    set_column("call.mosaic_scores.tsv", "score", lambda v: repr(float(v) - 1.0))(d)


def common_group(off, on):
    """The sequence_candidate_id, in the JP-on run, of a labelling that both runs score (matched by labelling)."""
    labs = {tuple(sorted((r["hap1_alleles"], r["hap2_alleles"]))) for r in T(f"{off}/call.mosaic_candidates.tsv")}
    return next(r["sequence_candidate_id"] for r in T(f"{on}/call.mosaic_candidates.tsv")
                if tuple(sorted((r["hap1_alleles"], r["hap2_alleles"]))) in labs)


