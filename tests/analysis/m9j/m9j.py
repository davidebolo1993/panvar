def m9i_module():
    m = types.ModuleType("m9i")
    argv = sys.argv
    sys.argv = ["m9i.py", "__definitions_only__", os.path.join(out, ".m9i_noop")]
    exec(compile(open(os.path.join(HERE, "..", "m9i", "m9i.py")).read(), "m9i.py", "exec"), m.__dict__)
    sys.argv = argv
    return m


def close(a, b, rel):
    """Declared tolerance: zero iff zero (tiny nonzero masses retained), else |a - b| <= rel * max(|a|, |b|)."""
    a, b = float(a), float(b)
    if a == 0.0 or b == 0.0:
        return a == b
    return abs(a - b) <= rel * max(abs(a), abs(b))


