def compare_dirs(a, b, declared_extra):
    """Every file of a (off) against b (on), each arm's own prefix normalised. Returns rows."""
    rows = []
    fa = {f[len("call."):]: f for f in os.listdir(a) if f.startswith("call.")}
    fb = {f[len("call."):]: f for f in os.listdir(b) if f.startswith("call.")}
    for k in sorted(set(fa) | set(fb)):
        if k in VOLATILE_FILES:
            continue
        if k not in fa or k not in fb:
            rows.append(dict(file=k, identical=k in declared_extra and k not in fa, detail="only in " + ("on" if k not in fa else "off")))
            continue
        pa, pb = f"{a}/{fa[k]}", f"{b}/{fb[k]}"
        ta, tb = open(pa).read().replace(f"{a}/call", "<P>"), open(pb).read().replace(f"{b}/call", "<P>")
        if k == "repair_rounds.tsv":
            same = [[r.get(c) for c in ROUND_COLS] for r in T(pa)] == [[r.get(c) for c in ROUND_COLS] for r in T(pb)]
            rows.append(dict(file=k + " (scientific columns)", identical=same))
        elif k == "tie_branches.tsv":
            same = [[r.get(c) for c in BRANCH_COLS] for r in T(pa)] == [[r.get(c) for c in BRANCH_COLS] for r in T(pb)]
            rows.append(dict(file=k + " (scientific columns)", identical=same))
        elif k in ("mosaic_status.tsv", "dosage_status.tsv", "settings.tsv"):
            ka = {l.split("\t")[0]: l.split("\t")[1:] for l in ta.splitlines() if "\t" in l}
            kb = {l.split("\t")[0]: l.split("\t")[1:] for l in tb.splitlines() if "\t" in l}
            diff = [x for x in set(ka) | set(kb) if ka.get(x) != kb.get(x)]
            undeclared = [x for x in diff if not (x.startswith("compound_") or VOLATILE_STATUS.search(x) or (k == "settings.tsv" and x == "profile"))]
            rows.append(dict(file=k + " (keys)", identical=not undeclared, detail=("declared differences: " + ",".join(sorted(x for x in diff if x not in undeclared))[:300]
                                                                                 + (" | UNDECLARED: " + ",".join(sorted(undeclared)) if undeclared else ""))))
        else:
            rows.append(dict(file=k, identical=ta == tb))
    return rows


